create policy results_admin_all on public.results for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists results_teacher_assigned_class on public.results;
create policy results_teacher_assigned_class on public.results for all using (
  exists (
    select 1 from public.students s join public.classes c on c.id = s.class_id
    join public.profiles p on p.id = auth.uid()
    where s.id = results.student_id and c.teacher_id = auth.uid() and p.role = 'teacher'
  )
) with check (recorded_by = auth.uid());
drop policy if exists results_student_read on public.results;
create policy results_student_read on public.results for select using (
  exists (select 1 from public.students s where s.id = results.student_id and s.profile_id = auth.uid())
);

