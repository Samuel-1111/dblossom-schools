create index if not exists complaints_status_idx on public.complaints(status);

create or replace function public.resolve_portal_login(identifier text, portal_type text)
returns table (login_email text)
language sql
stable
security definer
set search_path = public
as $$
  select pc.login_email
  from public.portal_credentials pc
  where pc.login_identifier = identifier
    and pc.credential_type = portal_type
  limit 1;
$$;

grant execute on function public.resolve_portal_login(text, text) to anon, authenticated;

