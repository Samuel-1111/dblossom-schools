create table if not exists public.portal_credentials (
  id bigint generated by default as identity primary key,
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  login_identifier text not null unique,
  login_email text not null unique,
  credential_type text not null check (credential_type in ('student', 'teacher', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  student_name text not null,
  class_name text not null,
  term text not null,
  session text not null,
  subjects jsonb not null default '[]'::jsonb,
  total_score numeric not null default 0,
  average numeric not null default 0,
  overall_percentage numeric not null default 0,
  teacher_comment text,
  principal_comment text,
  recorded_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  student_name text not null,
  admission_number text,
  amount numeric not null default 0,
  payment_method text,
  reference text,
  proof_url text,
  status text not null default 'Pending' check (status in ('Pending', 'Confirmed', 'Rejected')),
  submitted_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  event_date date not null,
  image_url text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_images (
  id bigint generated by default as identity primary key,
  title text not null,
  alt_text text,
  image_url text not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  phone text,
  subject text not null,
  message text not null,
  status text not null default 'New' check (status in ('New', 'In Progress', 'Resolved')),
  created_at timestamptz not null default now()
);

create index if not exists results_student_term_session_idx on public.results(student_id, term, session);
create index if not exists payments_status_idx on public.payments(status);
