-- 0012_school_platform_expansion.sql
-- Non-destructive expansion for parent portal, fees, communications, learning,
-- admissions, analytics support, permissions and school operations.
-- No existing school data is deleted.

create table if not exists public.academic_sessions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  start_date date,
  end_date date,
  is_current boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.terms (
  id bigint generated by default as identity primary key,
  session_id bigint references public.academic_sessions(id) on delete cascade,
  name text not null,
  start_date date,
  end_date date,
  is_current boolean not null default false,
  created_at timestamptz not null default now(),
  unique(session_id, name)
);

alter table public.announcements
  add column if not exists audience text not null default 'all',
  add column if not exists target_class_id bigint references public.classes(id) on delete set null,
  add column if not exists target_student_id bigint references public.students(id) on delete cascade,
  add column if not exists pinned boolean not null default false,
  add column if not exists status text not null default 'Published',
  add column if not exists publish_at timestamptz;

create index if not exists announcements_audience_idx on public.announcements(audience, status, pinned);
create index if not exists announcements_target_student_idx on public.announcements(target_student_id);

create table if not exists public.parent_notifications (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid not null references public.parent_profiles(id) on delete cascade,
  title text not null,
  body text not null,
  type text not null default 'general',
  link text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists parent_notifications_parent_idx on public.parent_notifications(parent_id, created_at desc);

create table if not exists public.parent_notification_preferences (
  parent_id uuid primary key references public.parent_profiles(id) on delete cascade,
  fee_notifications boolean not null default true,
  result_notifications boolean not null default true,
  attendance_notifications boolean not null default true,
  assignment_notifications boolean not null default true,
  event_notifications boolean not null default true,
  message_notifications boolean not null default true,
  whatsapp_notifications boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.parent_messages (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references public.parent_profiles(id) on delete set null,
  sender_profile_id uuid references public.profiles(id) on delete set null,
  recipient_profile_id uuid references public.profiles(id) on delete set null,
  student_id bigint references public.students(id) on delete set null,
  subject text,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists parent_messages_parent_idx on public.parent_messages(parent_id, created_at desc);
create index if not exists parent_messages_recipient_idx on public.parent_messages(recipient_profile_id, created_at desc);

create table if not exists public.parent_calendar_events (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  event_date date not null,
  start_time time,
  end_time time,
  audience text not null default 'all',
  class_id bigint references public.classes(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists parent_calendar_events_date_idx on public.parent_calendar_events(event_date);

create table if not exists public.fee_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text,
  default_amount numeric(12,2) not null default 0 check (default_amount >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.fee_invoices (
  id uuid primary key default gen_random_uuid(),
  student_id bigint not null references public.students(id) on delete cascade,
  session_id bigint references public.academic_sessions(id) on delete set null,
  term_id bigint references public.terms(id) on delete set null,
  invoice_number text not null unique,
  due_date date,
  status text not null default 'Unpaid' check (status in ('Draft','Unpaid','Partially Paid','Paid','Overdue','Cancelled')),
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  amount_paid numeric(12,2) not null default 0 check (amount_paid >= 0),
  balance numeric(12,2) not null default 0 check (balance >= 0),
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists fee_invoices_student_idx on public.fee_invoices(student_id, created_at desc);
create index if not exists fee_invoices_status_due_idx on public.fee_invoices(status, due_date);

create table if not exists public.fee_invoice_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.fee_invoices(id) on delete cascade,
  category_id uuid references public.fee_categories(id) on delete set null,
  description text not null,
  amount numeric(12,2) not null check (amount >= 0),
  created_at timestamptz not null default now()
);
create index if not exists fee_invoice_items_invoice_idx on public.fee_invoice_items(invoice_id);

create table if not exists public.fee_payments (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.fee_invoices(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  parent_id uuid references public.parent_profiles(id) on delete set null,
  amount numeric(12,2) not null check (amount > 0),
  method text not null default 'Paystack',
  reference text unique,
  status text not null default 'Pending' check (status in ('Pending','Confirmed','Failed','Reversed')),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists fee_payments_invoice_idx on public.fee_payments(invoice_id, created_at desc);
create index if not exists fee_payments_student_idx on public.fee_payments(student_id, created_at desc);

create table if not exists public.fee_receipts (
  id uuid primary key default gen_random_uuid(),
  payment_id uuid not null unique references public.fee_payments(id) on delete cascade,
  receipt_number text not null unique,
  issued_at timestamptz not null default now()
);

create table if not exists public.student_documents (
  id uuid primary key default gen_random_uuid(),
  student_id bigint not null references public.students(id) on delete cascade,
  title text not null,
  document_type text not null default 'Other',
  file_url text not null,
  uploaded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists student_documents_student_idx on public.student_documents(student_id, created_at desc);

create table if not exists public.student_promotions (
  id uuid primary key default gen_random_uuid(),
  student_id bigint not null references public.students(id) on delete cascade,
  from_class_id bigint references public.classes(id) on delete set null,
  to_class_id bigint references public.classes(id) on delete set null,
  from_session_id bigint references public.academic_sessions(id) on delete set null,
  to_session_id bigint references public.academic_sessions(id) on delete set null,
  status text not null default 'Promoted' check (status in ('Promoted','Repeated','Pending')),
  promoted_at timestamptz not null default now(),
  promoted_by uuid references public.profiles(id) on delete set null
);
create index if not exists student_promotions_student_idx on public.student_promotions(student_id, promoted_at desc);

create table if not exists public.result_locks (
  id uuid primary key default gen_random_uuid(),
  class_id bigint references public.classes(id) on delete cascade,
  term_id bigint references public.terms(id) on delete cascade,
  locked boolean not null default true,
  locked_by uuid references public.profiles(id) on delete set null,
  locked_at timestamptz not null default now(),
  unique(class_id, term_id)
);

create table if not exists public.staff_permissions (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  permission text not null,
  allowed boolean not null default true,
  unique(profile_id, permission)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_profile_id uuid references public.profiles(id) on delete set null,
  action text not null,
