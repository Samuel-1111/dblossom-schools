-- Teachers can manage classroom content for their assigned classes.
create policy assignments_teacher on public.assignments for all to authenticated using (
  exists (select 1 from public.teachers t join public.classes c on c.name=t.assigned_class where t.profile_id=auth.uid() and c.id=assignments.class_id)
) with check (
  exists (select 1 from public.teachers t join public.classes c on c.name=t.assigned_class where t.profile_id=auth.uid() and c.id=assignments.class_id)
);
