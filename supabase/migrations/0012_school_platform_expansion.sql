create policy fee_invoices_parent_read on public.fee_invoices for select to authenticated using (
  exists (select 1 from public.parent_student_links l join public.parent_profiles p on p.id=l.parent_id where l.student_id=fee_invoices.student_id and p.profile_id=auth.uid())
);
create policy fee_invoice_items_parent_read on public.fee_invoice_items for select to authenticated using (
  exists (select 1 from public.fee_invoices i join public.parent_student_links l on l.student_id=i.student_id join public.parent_profiles p on p.id=l.parent_id where i.id=fee_invoice_items.invoice_id and p.profile_id=auth.uid())
);
create policy fee_payments_parent_read on public.fee_payments for select to authenticated using (
  exists (select 1 from public.parent_student_links l join public.parent_profiles p on p.id=l.parent_id where l.student_id=fee_payments.student_id and p.profile_id=auth.uid())
